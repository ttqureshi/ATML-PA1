def load(path: Path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def pct(x: float, nd: int = 1) -> str:
    return f"{100 * x:.{nd}f}"


def signed_pct(x: float, nd: int = 1) -> str:
    v = 100 * x
    if abs(v) < 0.5 * 10 ** (-nd):
        v = 0.0
    return f"${v:+.{nd}f}$"


def write_table(name: str, sources: list[Path], body: str) -> None:
    header = (
        f"% Auto-generated by report/scripts/make_report_assets.py. Do not edit by hand.\n"
        f"% Sources: {', '.join(rel(s) for s in sources)}\n"
    )
    (OUT_T / f"{name}.tex").write_text(header + body, encoding="utf-8")
    print(f"table  {name}.tex")


def tabular(colspec: str, head: list[str], rows: list[list[str]], extra_head: str = "") -> str:
    lines = [f"\\begin{{tabular}}{{{colspec}}}", "\\toprule"]
    if extra_head:
        lines.append(extra_head)
    lines.append(" & ".join(head) + " \\\\")
    lines.append("\\midrule")
    for r in rows:
        if r == ["MIDRULE"]:
            lines.append("\\midrule")
        else:
            lines.append(" & ".join(r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(lines)


