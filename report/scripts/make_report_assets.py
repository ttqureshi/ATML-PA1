def perclass_table_and_figure() -> None:
    accs, counts = {}, {}
    confs = {}
    for name, path, key in PERCLASS_RUNS:
        d = load(path)
        accs[name] = {c: d[key][c]["accuracy"] for c in PACS_CLASSES}
        counts = {c: d[key][c]["n"] for c in PACS_CLASSES}
        confs[name] = d.get("target_confusions_top") or d.get("sketch_confusions_top")

    base = accs["ERM"]
    rows = []
    for c in PACS_CLASSES:
        row = [f"{c} ({counts[c]})", pct(base[c])]
        for name, _, _ in PERCLASS_RUNS[1:]:
            row.append(f"{pct(accs[name][c])} ({signed_pct(accs[name][c] - base[c])})")
        rows.append(row)
    extra = (
        " & & \\multicolumn{3}{c}{Task 2 (sees unlabeled Sketch)} & \\multicolumn{2}{c}{Task 3 (Sketch unseen)} \\\\\n"
        "\\cmidrule(lr){3-5}\\cmidrule(lr){6-7}"
    )
    write_table(
        "t23_perclass",
        [p for _, p, _ in PERCLASS_RUNS],
        "% cells: Sketch per-class accuracy (change vs ERM), in percent; (n) = Sketch images per class\n"
        + tabular("lcccccc", ["Class ($n$)"] + [n for n, _, _ in PERCLASS_RUNS], rows, extra_head=extra),
    )

    rows = []
    for name, _, _ in PERCLASS_RUNS:
        top = confs[name][:3]
        rows.append([name] + [f"{t['true']}$\\to${t['pred']} ({t['count']})" for t in top])
    write_table(
        "t23_confusions",
        [p for _, p, _ in PERCLASS_RUNS],
        tabular("llll", ["Model", "1st", "2nd", "3rd"], rows),
    )

    fig, axes = plt.subplots(1, 2, figsize=(TEXTWIDTH_IN, 1.9), sharey=True)
    groups = [(axes[0], ["DAN", "DANN", "CDAN"], "Task 2 (UDA) vs. ERM"), (axes[1], ["DAN-DG", "SAM"], "Task 3 (DG) vs. ERM")]
    xs = range(len(PACS_CLASSES))
    for ax, names, title in groups:
        w = 0.8 / len(names)
        for i, name in enumerate(names):
            ax.bar(
                [x - 0.4 + w * (i + 0.5) for x in xs],
                [100 * (accs[name][c] - base[c]) for c in PACS_CLASSES],
                width=w,
                label=name,
            )
        ax.axhline(0, color="k", lw=0.6)
        ax.set_xticks(list(xs))
        ax.set_xticklabels(PACS_CLASSES, rotation=35, ha="right")
        ax.set_title(title)
        ax.grid(axis="y", alpha=0.3, lw=0.5)
        ax.legend(frameon=False, fontsize=6.5)
    axes[0].set_ylabel("$\\Delta$ Sketch accuracy (pp)")
    fig.tight_layout(w_pad=0.8)
    fig.savefig(OUT_F / "t23_perclass_delta.pdf")
    plt.close(fig)
    print("figure t23_perclass_delta.pdf")


