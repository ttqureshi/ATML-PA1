SCORE_NAMES = {"msp": "MSP", "mls": "MLS", "energy": "Energy", "mahalanobis": "Mahalanobis", "proser_placeholder": "PROSER placeholder"}
MODEL_NAMES = {"vanilla": "Vanilla", "gcsc": "GCSC", "proser": "PROSER"}


def osr_cells(r: dict) -> list[str]:
    return [
        pct(r["auroc_near"]),
        pct(r["auroc_far"]),
        pct(r["auroc_all"]),
        pct(r["known_test_accept_rate"]),
        pct(r["near_reject_rate"]),
        pct(r["far_reject_rate"]),
        pct(r["near_fpr_at_95tpr"]),
        pct(r["far_fpr_at_95tpr"]),
    ]


OSR_EXTRA = (
    "\\multicolumn{3}{c}{AUROC (\\%)} & \\multicolumn{3}{c}{At $\\tau$ = val. 95th pct. (\\%)} & \\multicolumn{2}{c}{FPR@95TPR (\\%)} \\\\\n"
)


