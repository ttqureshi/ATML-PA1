def curve_panels(runs: list[tuple[Path, str]], out_name: str, align_label: str, worst: bool = False) -> None:
    n = 4 if worst else 3
    fig, axes = plt.subplots(1, n, figsize=(TEXTWIDTH_IN, 1.7))
    for path, label in runs:
        h = load(path)
        ep = [r["epoch"] for r in h]
        f1 = [100 * r["source_val"]["mean_macro_f1"] for r in h]
        best = max(range(len(f1)), key=lambda i: f1[i])
        (line,) = axes[0].plot(ep, [r["train"]["cls_loss"] for r in h], lw=1, label=label)
        c = line.get_color()
        align = [r["train"]["align_loss"] for r in h]
        if any(a != 0 for a in align):
            axes[1].plot(ep, align, lw=1, color=c)
        axes[2].plot(ep, f1, lw=1, color=c)
        axes[2].plot(ep[best], f1[best], marker="*", ms=6, color=c)
        if worst:
            wf = [100 * min(v["macro_f1"] for v in r["source_val"]["per_domain"].values()) for r in h]
            axes[3].plot(ep, wf, lw=1, color=c)
            axes[3].plot(ep[best], wf[best], marker="*", ms=6, color=c)
    titles = ["Classification loss", align_label, "Mean source-val macro-F1 (%)"]
    if worst:
        titles.append("Worst source-val macro-F1 (%)")
    for ax, t in zip(axes, titles):
        ax.set_title(t)
        ax.set_xlabel("Epoch")
        ax.grid(alpha=0.3, lw=0.5)
    axes[1].set_yscale("log")
    fig.legend(*axes[0].get_legend_handles_labels(), loc="upper center", ncol=len(runs), frameon=False, bbox_to_anchor=(0.5, 1.12))
    fig.tight_layout(w_pad=0.6)
    fig.savefig(OUT_F / out_name)
    plt.close(fig)
    print(f"figure {out_name}")


