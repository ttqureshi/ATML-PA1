            f"{fs[k]['grayscale']:.3f}",
            f"{fs[k]['cue_conflict_vs_content']:.3f}",
            f"{fs[k]['translation_16px_right']:.3f}",
            f"{fs[k]['patch_shuffle']:.3f}",
